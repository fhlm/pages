def title_row(ws, ncols, text, row=1, fill=C_HEAD, height=30):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=YAHEI, size=14, bold=True, color="FFFFFF")
    c.fill = PatternFill("solid", fgColor=fill)
    c.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[row].height = height

def header(ws, row, headers):
    for i, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = Font(name=YAHEI, size=10.5, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=C_HEAD)
        c.alignment = Alignment(horizontal="center", vertical="center")
        c.border = BORDER
    ws.row_dimensions[row].height = 22

def put(ws, row, values, fills=None, bolds=None, wrap=True):
    for i, v in enumerate(values, 1):
        c = ws.cell(row=row, column=i, value=v)
        c.font = Font(name=YAHEI, size=10.5, bold=bool(bolds and i in bolds))
        c.alignment = Alignment(vertical="center", wrap_text=wrap,
                                horizontal="center" if i == 1 or (isinstance(v, (int, float))) else "left")
        c.border = BORDER
        if fills and i in fills:
            c.fill = PatternFill("solid", fgColor=fills[i])

